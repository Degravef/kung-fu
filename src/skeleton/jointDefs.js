/**
 * Stickboy skeleton definition — pure data, no three.js import, so it can be
 * reused from Node (tests, an LLM-output validator, a move compiler…).
 *
 * COORDINATES (metres). +Y is up, +Z is the way the character faces and
 * +X is the character's LEFT. The rest pose is "standing at attention, arms
 * hanging": every joint rotation is the identity, so each `offset` is simply
 * the vector from the parent joint to this joint.
 *
 * ROTATION CHANNELS. A joint is rotated by named, anatomical channels
 * (`flex`, `abd`, `twist`, …) given in degrees:
 *
 *     pose.joints.elbow_R = { flex: 90 }       // not "rotate x by -1.57"
 *
 * Each channel maps to a local axis and a sign. `dof` is listed
 * outermost-first: q = q(dof[0]) · q(dof[1]) · …, so the LAST channel is
 * applied first (it is the innermost rotation).
 *
 * LEFT / RIGHT. Only the centre line and the LEFT side are written by hand;
 * the right side is generated by `mirror()`. Mirroring flips the x offset and
 * the sign of y/z-axis channels (x-axis rotations are mirror-invariant), which
 * means one channel value has the SAME meaning on both sides:
 * `{ shoulder_L: { abd: 90 }, shoulder_R: { abd: 90 } }` raises both arms out
 * to the sides symmetrically.
 *
 * POLE: shoulder/hip use flex·abd·twist Euler order, so at abd = 90° the arm/leg lies
 * on the flex axis and `flex` only spins it. Reach overhead with flex (up to 180°)
 * rather than abd > 90°; for a raised side arm use abd 90 and put the rest in `twist`.
 */

/** Hands are drawn larger than life so that finger joints are readable. */
export const HAND_SCALE = 1.5;

/** Channel descriptor: which local axis, which sign, what range, what it means. */
const D = (channel, axis, sign, min, max, label) => ({ channel, axis, sign, min, max, label });

const stripSide = (label) => label.replace(/^(Left|Right) /, '').replace(/^./, (c) => c.toUpperCase());

function node(name, label, parent, offset, o = {}) {
  const dof = o.dof ?? [];
  return {
    name,
    label,
    short: o.short ?? stripSide(label),
    parent,
    offset,
    region: o.region ?? 'Body',
    part: o.part ?? null,
    side: name.endsWith('_L') ? 'L' : name.endsWith('_R') ? 'R' : 'C',
    kind: dof.length ? 'joint' : 'end', // end = tip / landmark, nothing to rotate
    radius: o.radius ?? 0.025,
    boneRadius: o.boneRadius ?? 0.014,
    dof,
  };
}

