/* ------------------------------------------------------------ mirror / build */

const toRight = (s) => s.replace(/_L$/, '_R');

function mirror(def) {
  return {
    ...def,
    name: toRight(def.name),
    label: def.label.replace(/\bLeft\b/g, 'Right'),
    parent: def.parent?.endsWith('_L') ? toRight(def.parent) : def.parent,
    offset: [-def.offset[0], def.offset[1], def.offset[2]],
    region: def.region.replace('Left', 'Right'),
    side: 'R',
    dof: def.dof.map((d) => ({ ...d, sign: d.axis === 'x' ? d.sign : -d.sign })),
  };
}

